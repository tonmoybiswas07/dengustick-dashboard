"use client";

import {
  FileText,
  Download,
  CalendarDays,
  MapPin,
  UserRound,
} from "lucide-react";

import { Button } from "@/components/ui/button";

import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
  DialogDescription,
  DialogFooter,
} from "@/components/ui/dialog";

import {
  Table,
  TableHeader,
  TableBody,
  TableHead,
  TableRow,
  TableCell,
} from "@/components/ui/table";

import { reportTypeLabels } from "@/app/constants/report";
import type { ReportDTO } from "@/app/types/report";

interface ReportPreviewProps {
  report: ReportDTO | null;
  canExport: boolean;
  onClose: () => void;
  onDownload: (
    id: string,
    format: "pdf" | "csv"
  ) => void;
}

export default function ReportPreview({
  report,
  canExport,
  onClose,
  onDownload,
}: ReportPreviewProps) {
  return (
    <Dialog
      open={Boolean(report)}
      onOpenChange={(open) => {
        if (!open) onClose();
      }}
    >
      <DialogContent className="max-h-[90dvh] overflow-y-auto sm:max-w-5xl">
        {report && (
          <>
            <DialogHeader>
              <DialogTitle className="flex items-center gap-2">
                <FileText className="size-5 text-primary" />
                {report.title}
              </DialogTitle>

              <DialogDescription>
                {reportTypeLabels[report.type]}
              </DialogDescription>
            </DialogHeader>

            <div className="space-y-6">
              <div className="space-y-2 rounded-xl border bg-muted/30 p-4">
                <p className="flex items-center gap-2 text-sm">
                  <CalendarDays className="size-4 text-primary" />

                  {report.filters.startDate} to{" "}
                  {report.filters.endDate}
                </p>

                <p className="flex items-center gap-2 text-sm">
                  <MapPin className="size-4 text-primary" />

                  {report.filters.district === "all"
                    ? "All Districts"
                    : report.filters.district}
                </p>

                <p className="flex items-center gap-2 text-sm">
                  <UserRound className="size-4 text-primary" />

                  Generated by {report.generatedByName}
                </p>

                <p className="text-xs text-muted-foreground">
                  Region: {report.regionId ?? "All Regions"}
                </p>
              </div>

              <div>
                <h3 className="mb-3 font-semibold">
                  Report Summary
                </h3>

                <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-3">
                  {report.snapshot.metrics.map((item) => (
                    <div
                      key={item.label}
                      className="rounded-xl border p-4"
                    >
                      <p className="text-xs text-muted-foreground">
                        {item.label}
                      </p>

                      <p className="mt-2 text-2xl font-bold text-primary">
                        {item.value}
                      </p>
                    </div>
                  ))}
                </div>
              </div>

              <div>
                <h3 className="mb-3 font-semibold">
                  Detailed Statistics
                </h3>

                <div className="overflow-x-auto rounded-xl border">
                  <Table>
                    <TableHeader>
                      <TableRow className="bg-muted/50">
                        {report.snapshot.columns.map(
                          (column) => (
                            <TableHead key={column}>
                              {column}
                            </TableHead>
                          )
                        )}
                      </TableRow>
                    </TableHeader>

                    <TableBody>
                      {report.snapshot.rows.length === 0 ? (
                        <TableRow>
                          <TableCell
                            colSpan={
                              report.snapshot.columns.length
                            }
                            className="py-10 text-center text-muted-foreground"
                          >
                            No matching records.
                          </TableCell>
                        </TableRow>
                      ) : (
                        report.snapshot.rows.map(
                          (row, index) => (
                            <TableRow key={index}>
                              {row.map((cell, cellIndex) => (
                                <TableCell key={cellIndex}>
                                  {cell}
                                </TableCell>
                              ))}
                            </TableRow>
                          )
                        )
                      )}
                    </TableBody>
                  </Table>
                </div>
              </div>

              <p className="text-xs leading-relaxed text-muted-foreground">
                This report is a saved snapshot of surveillance
                records at the time of generation. Positive
                detections do not represent human dengue
                infection rates.
              </p>
            </div>

            <DialogFooter>
              <Button
                variant="outline"
                onClick={onClose}
              >
                Close
              </Button>

              {canExport && (
                <>
                  <Button
                    variant="outline"
                    onClick={() =>
                      onDownload(report._id, "csv")
                    }
                  >
                    <Download className="size-4" />
                    Export CSV
                  </Button>

                  <Button
                    onClick={() =>
                      onDownload(report._id, "pdf")
                    }
                  >
                    <Download className="size-4" />
                    Download PDF
                  </Button>
                </>
              )}
            </DialogFooter>
          </>
        )}
      </DialogContent>
    </Dialog>
  );
}