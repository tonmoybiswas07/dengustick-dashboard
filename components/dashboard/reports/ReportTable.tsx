"use client";

import {
  FileText,
  Eye,
  FileDown,
  MoreHorizontal,
} from "lucide-react";

import { Card } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";

import {
  Table,
  TableHeader,
  TableBody,
  TableRow,
  TableHead,
  TableCell,
} from "@/components/ui/table";

import {
  DropdownMenu,
  DropdownMenuTrigger,
  DropdownMenuContent,
  DropdownMenuItem,
} from "@/components/ui/dropdown-menu";

import {
  reportTypeLabels,
  reportTypeColors,
} from "@/app/constants/report";

import type { ReportListItem } from "@/app/types/report";

interface ReportTableProps {
  reports: ReportListItem[];
  canExport: boolean;
  onPreview: (id: string) => void;
  onDownload: (
    id: string,
    format: "pdf" | "csv"
  ) => void;
}

export default function ReportTable({
  reports,
  canExport,
  onPreview,
  onDownload,
}: ReportTableProps) {
  return (
    <Card className="gap-0 overflow-hidden py-0">
      <div className="overflow-x-auto">
        <Table>
          <TableHeader>
            <TableRow className="bg-muted/40">
              <TableHead>Report</TableHead>
              <TableHead>Type</TableHead>
              <TableHead>Period</TableHead>
              <TableHead>District</TableHead>
              <TableHead>Generated By</TableHead>
              <TableHead>Created At</TableHead>

              <TableHead className="text-right">
                Actions
              </TableHead>
            </TableRow>
          </TableHeader>

          <TableBody>
            {reports.length === 0 ? (
              <TableRow>
                <TableCell colSpan={7}>
                  <div className="flex flex-col items-center gap-3 py-16">
                    <FileText className="size-12 text-muted-foreground" />

                    <h3 className="font-semibold">
                      No reports found
                    </h3>

                    <p className="text-sm text-muted-foreground">
                      Generated reports will appear here.
                    </p>
                  </div>
                </TableCell>
              </TableRow>
            ) : (
              reports.map((report) => (
                <TableRow key={report._id}>
                  <TableCell>
                    <div className="flex min-w-48 items-center gap-3">
                      <div className="flex size-10 shrink-0 items-center justify-center rounded-lg bg-primary/10">
                        <FileText className="size-5 text-primary" />
                      </div>

                      <div>
                        <p className="font-medium">
                          {report.title}
                        </p>

                        <p className="text-xs text-muted-foreground">
                          {report.reportId.slice(0, 13)}
                        </p>
                      </div>
                    </div>
                  </TableCell>

                  <TableCell>
                    <Badge
                      variant="outline"
                      className={reportTypeColors[report.type]}
                    >
                      {reportTypeLabels[report.type]}
                    </Badge>
                  </TableCell>

                  <TableCell>
                    <div className="whitespace-nowrap text-xs">
                      <p>{report.filters.startDate}</p>
                      <p className="text-muted-foreground">
                        to {report.filters.endDate}
                      </p>
                    </div>
                  </TableCell>

                  <TableCell>
                    {report.filters.district === "all"
                      ? "All Districts"
                      : report.filters.district}
                  </TableCell>

                  <TableCell>
                    {report.generatedByName}
                  </TableCell>

                  <TableCell>
                    {new Date(
                      report.createdAt
                    ).toLocaleDateString("en-GB", {
                      timeZone: "Asia/Dhaka",
                    })}
                  </TableCell>

                  <TableCell className="text-right">
                    <DropdownMenu>
                      <DropdownMenuTrigger
                        render={
                          <Button
                            variant="ghost"
                            size="icon"
                            aria-label="Report actions"
                          />
                        }
                      >
                        <MoreHorizontal className="size-4" />
                      </DropdownMenuTrigger>

                      <DropdownMenuContent align="end">
                        <DropdownMenuItem
                          onClick={() =>
                            onPreview(report._id)
                          }
                        >
                          <Eye className="size-4" />
                          Preview Report
                        </DropdownMenuItem>

                        {canExport && (
                          <>
                            <DropdownMenuItem
                              onClick={() =>
                                onDownload(
                                  report._id,
                                  "pdf"
                                )
                              }
                            >
                              <FileDown className="size-4" />
                              Download PDF
                            </DropdownMenuItem>

                            <DropdownMenuItem
                              onClick={() =>
                                onDownload(
                                  report._id,
                                  "csv"
                                )
                              }
                            >
                              <FileDown className="size-4" />
                              Download CSV
                            </DropdownMenuItem>
                          </>
                        )}
                      </DropdownMenuContent>
                    </DropdownMenu>
                  </TableCell>
                </TableRow>
              ))
            )}
          </TableBody>
        </Table>
      </div>
    </Card>
  );
}