import "server-only";

import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";

import { reportTypeLabels } from "@/app/constants/report";
import type { Report } from "@/app/types/report";

function escapeCSV(value: string | number) {
  let text = String(value);

  if (
    typeof value === "string" &&
    /^[\s\u0000-\u001f]*[=+\-@]/.test(text)
  ) {
    text = `'${text}`;
  }

  return `"${text.replaceAll('"', '""')}"`;
}

export function generateCSV(report: Omit<Report, "_id">) {
  const rows: (string | number)[][] = [
    ["DengueVision Surveillance Report"],
    ["Report ID", report.reportId],
    ["Title", report.title],
    ["Type", reportTypeLabels[report.type]],
    ["Generated By", report.generatedByName],
    ["Generated At", report.createdAt.toISOString()],
    ["Start Date", report.filters.startDate],
    ["End Date", report.filters.endDate],
    ["District", report.filters.district],
    ["Region", report.regionId ?? "All Regions"],
    [],
    ["Summary", "Value"],

    ...report.snapshot.metrics.map((item) => [
      item.label,
      item.value,
    ]),

    [],
    report.snapshot.columns,
    ...report.snapshot.rows,
    [],
    [
      "Surveillance statistics do not represent human dengue infection rates.",
    ],
  ];

  return (
    "\uFEFF" +
    rows
      .map((row) =>
        row.map(escapeCSV).join(",")
      )
      .join("\r\n")
  );
}

export function generatePDF(report: Omit<Report, "_id">) {
  const doc = new jsPDF({
    orientation: "landscape",
    unit: "mm",
    format: "a4",
  });

  const pageWidth =
    doc.internal.pageSize.getWidth();

  doc.setFillColor(13, 148, 136);
  doc.rect(0, 0, pageWidth, 25, "F");

  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(21);

  doc.text("DengueVision", 14, 11);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);

  doc.text(
    "Mosquito Larvae Surveillance System",
    14,
    18
  );

  doc.setTextColor(30, 41, 59);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);

  const titleLines = doc.splitTextToSize(
    report.title,
    pageWidth - 28
  );

  doc.text(titleLines, 14, 36);

  const metadataY =
    36 + titleLines.length * 7;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);

  doc.text(
    [
      `Report ID: ${report.reportId}`,
      `Type: ${reportTypeLabels[report.type]}`,
      `Period: ${report.filters.startDate} to ${report.filters.endDate}`,
      `District: ${report.filters.district === "all" ? "All Districts" : report.filters.district}`,
      `Region: ${report.regionId ?? "All Regions"}`,
      `Generated By: ${report.generatedByName}`,
      `Generated At: ${report.createdAt.toLocaleString("en-GB", { timeZone: "Asia/Dhaka" })}`,
    ],
    14,
    metadataY
  );

  autoTable(doc, {
    startY: metadataY + 34,

    head: [["Summary Metric", "Value"]],

    body: report.snapshot.metrics.map((item) => [
      item.label,
      String(item.value),
    ]),

    theme: "grid",

    headStyles: {
      fillColor: [13, 148, 136],
      textColor: 255,
    },

    styles: {
      fontSize: 10,
      cellPadding: 3,
      overflow: "linebreak",
    },

    margin: {
      left: 14,
      right: 14,
      bottom: 20,
    },
  });

  autoTable(doc, {
    head: [report.snapshot.columns],

    body: report.snapshot.rows.length
      ? report.snapshot.rows.map((row) =>
          row.map(String)
        )
      : [
          [
            "No matching records",
            ...report.snapshot.columns
              .slice(1)
              .map(() => ""),
          ],
        ],

    theme: "striped",

    headStyles: {
      fillColor: [13, 148, 136],
      textColor: 255,
    },

    styles: {
      fontSize: 9,
      cellPadding: 3,
      overflow: "linebreak",
    },

    margin: {
      left: 14,
      right: 14,
      bottom: 20,
    },
  });

  const pageCount = doc.getNumberOfPages();

  for (let page = 1; page <= pageCount; page++) {
    doc.setPage(page);

    const pageHeight =
      doc.internal.pageSize.getHeight();

    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);

    doc.text(
      "Surveillance data does not represent human dengue infection rates.",
      14,
      pageHeight - 12
    );

    doc.text(
      `Page ${page} of ${pageCount}`,
      pageWidth - 14,
      pageHeight - 7,
      { align: "right" }
    );
  }

  return doc.output("arraybuffer");
}